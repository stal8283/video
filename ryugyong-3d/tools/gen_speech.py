"""Writes src/short/speech.gen.ts: the on-screen speakers' words (Guest, Clerk) and a per-frame loudness curve of
public/vo/voice.wav (30 fps), so talking mouths open on the syllables (leading the audio by 2 frames)."""
import json, subprocess
import numpy as np
W = json.load(open("vo/timings.json"))["words"]
SR = 48000
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "public/vo/voice.wav", "-f", "f32le", "-ac", "1", "-ar", str(SR), "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, dtype=np.float32)
hop = SR // 30
n = int(np.ceil(len(a) / hop))
rms = np.array([np.sqrt(np.mean(a[i * hop:(i + 1) * hop] ** 2) + 1e-12) for i in range(n)])
loud = np.clip(rms / np.percentile(rms, 98), 0, 1)
words = lambda spk: [[w["w"], w["t"], w["end"]] for w in W if w["spk"] == spk]
open("src/short/speech.gen.ts", "w").write(
    "// generated by tools/gen_speech.py; do not edit\n"
    f"export const GUEST_WORDS: [string, number, number][] = {json.dumps(words('guest'))};\n"
    f"export const CLERK_WORDS: [string, number, number][] = {json.dumps(words('clerk'))};\n"
    f"export const LOUD: number[] = {json.dumps([round(float(x), 2) for x in loud])};\n")
print(len(words('guest')), len(words('clerk')), n)
